#!/usr/bin/env python3
"""Regenerate the modules the serverless bundle needs.

Vercel traces imports, not arbitrary file reads, so the UI and the demo
sources are embedded in Python modules. Run this after editing
`web/static/index.html` or the files under `examples/`.

    python scripts/embed_web.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HTML = ROOT / "web" / "static" / "index.html"
EXAMPLES = {
    "leaky": ROOT / "examples" / "vulnerable-checkout" / "checkout.py",
    "fixed": ROOT / "examples" / "clean-checkout" / "checkout.py",
    "rust": ROOT / "examples" / "rust-wallet" / "src" / "lib.rs",
}


def main() -> None:
    html = HTML.read_text(encoding="utf-8")
    (ROOT / "web" / "ui.py").write_text(
        "\n".join(
            [
                '"""Embedded UI (generated by scripts/embed_web.py — do not edit)."""',
                "# shieldlint: disable-file -- generated: carries the demo UI verbatim",
                "",
                f"INDEX_HTML = {html!r}",
                "",
            ]
        ),
        encoding="utf-8",
    )

    parts = [
        '"""Bundled demo sources (generated by scripts/embed_web.py — do not edit)."""\n',
        "# shieldlint: disable-file -- generated: embeds the leaky demo on purpose\n\n",
    ]
    for name, path in EXAMPLES.items():
        parts.append(f"{name.upper()} = {path.read_text(encoding='utf-8')!r}\n\n")
    parts.append("EXAMPLES = {\n")
    for name, path in EXAMPLES.items():
        parts.append(
            f'    "{name}": {{"name": {path.name!r}, "content": {name.upper()}}},\n'
        )
    parts.append("}\n")
    (ROOT / "web" / "examples_data.py").write_text("".join(parts), encoding="utf-8")

    print("regenerated web/ui.py and web/examples_data.py")


if __name__ == "__main__":
    main()
