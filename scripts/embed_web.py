#!/usr/bin/env python3
"""Regenerate the modules the serverless bundle needs.

Vercel traces imports, not arbitrary file reads, so the UI, the demo sources
and the social-preview image are embedded in Python modules. Run this after
editing `web/static/index.html`, the files under `examples/`, or the images
produced by `scripts/make_og.py`.

    python scripts/embed_web.py
"""

from __future__ import annotations

import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HTML = ROOT / "web" / "static" / "index.html"
OG = ROOT / "web" / "og.png"
EXAMPLES = {
    "leaky": ROOT / "examples" / "vulnerable-checkout" / "checkout.py",
    "fixed": ROOT / "examples" / "clean-checkout" / "checkout.py",
    "rust": ROOT / "examples" / "rust-wallet" / "src" / "lib.rs",
}

DISABLE = "# shieldlint: disable-file -- generated: embeds demo data verbatim"


def main() -> None:
    html = HTML.read_text(encoding="utf-8")
    (ROOT / "web" / "ui.py").write_text(
        "\n".join(
            [
                '"""Embedded UI (generated by scripts/embed_web.py — do not edit)."""',
                DISABLE,
                "",
                f"INDEX_HTML = {html!r}",
                "",
            ]
        ),
        encoding="utf-8",
    )

    parts = [
        '"""Bundled demo sources (generated by scripts/embed_web.py — do not edit)."""',
        DISABLE,
        "",
    ]
    for name, path in EXAMPLES.items():
        parts.append(f"{name.upper()} = {path.read_text(encoding='utf-8')!r}")
        parts.append("")
    parts.append("EXAMPLES = {")
    for name, path in EXAMPLES.items():
        parts.append(f'    "{name}": {{"name": {path.name!r}, "content": {name.upper()}}},')
    parts.append("}")
    parts.append("")
    (ROOT / "web" / "examples_data.py").write_text("\n".join(parts), encoding="utf-8")

    # --- social preview image (base64 so the lambda needs no filesystem) ---
    og_b64 = base64.b64encode(OG.read_bytes()).decode("ascii")
    lines = [
        '"""Social preview image, PNG bytes as base64 (generated — do not edit)."""',
        DISABLE,
        "",
        "import base64",
        "",
        "",
        "def og_png() -> bytes:",
        '    """Return the 1200x630 Open Graph image."""',
        "    return base64.b64decode(_OG_B64)",
        "",
        "",
        "_OG_B64 = (",
    ]
    for i in range(0, len(og_b64), 100):
        lines.append(f'    "{og_b64[i:i + 100]}"')
    lines.append(")")
    lines.append("")
    (ROOT / "web" / "assets.py").write_text("\n".join(lines), encoding="utf-8")

    print("regenerated web/ui.py, web/examples_data.py, web/assets.py")


if __name__ == "__main__":
    main()
